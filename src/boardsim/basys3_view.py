"""Live Basys3 board view: your VHDL design runs in GHDL, the board is in the browser.

    browser page (web/basys3.html)  <--HTTP / server-sent events-->  this module
    this module                     <--stdin/stdout lines-->  GHDL: generated harness + your design

The harness (generated from your top entity's ports) runs the 100 MHz clock and works in
frames: it reads one line with the switch/button state and the frame length, simulates
that long while sampling the LEDs and the 7-segment display, and answers with one line:

    in : <frame_ns> <sw 0..65535> <buttons: C=1 U=2 L=4 R=8 D=16>
    out: @b3 <sim time us> <16 LED duty chars 0-f> <4 x 2 hex: digit segments+dp> <4 digit duty chars>

LED and digit "duty" is how often they were lit while sampled (0-f), so PWM dimming
and display multiplexing look like they do on the board. Port names follow Digilent's
Basys3 master XDC: clk, sw, btnC/U/L/R/D, led, seg, dp, an. Ports your design doesn't
have stay unconnected.
"""
import re
import subprocess
import sys
import threading
import time
from pathlib import Path

from . import ghdl, server

BOARD_INPUTS = {"clk", "sw", "btnc", "btnu", "btnl", "btnr", "btnd"}
BOARD_OUTPUTS = {"led", "seg", "dp", "an"}
BUTTONS = ["btnC", "btnU", "btnL", "btnR", "btnD"]          # bit 0..4 of the input word
FULL_WIDTH = {"sw": 16, "led": 16, "seg": 7, "an": 4}


# --- Finding the top entity and its ports ------------------------------------------
def _strip_comments(text):
    return re.sub(r"--[^\n]*", "", text)


def find_entity(src_dir, top):
    """(file, ports [(name, mode, width or None)], generic names) for entity `top`."""
    for f in sorted(Path(src_dir).glob("*.vhd")):
        text = _strip_comments(f.read_text(errors="replace"))
        m = re.search(rf"\bentity\s+{re.escape(top)}\s+is\b(.*?)\bend\b", text, re.I | re.S)
        if m:
            return f, _ports(m.group(1)), _generics(m.group(1))
    raise SystemExit(f"entity {top} not found in {src_dir}/*.vhd (use --top to name your top-level entity)")


def _clause(body, keyword):
    """Text inside `keyword ( ... )`, parentheses balanced."""
    m = re.search(rf"\b{keyword}\s*\(", body, re.I)
    if not m:
        return ""
    depth, i = 1, m.end()
    while depth and i < len(body):
        depth += {"(": 1, ")": -1}.get(body[i], 0)
        i += 1
    return body[m.end():i - 1]


def _generics(body):
    return [n.strip() for decl in _clause(body, "generic").split(";") if ":" in decl
            for n in decl.split(":", 1)[0].split(",")]


def _ports(body):
    ports = []
    for decl in _clause(body, "port").split(";"):
        if ":" not in decl:
            continue
        names, rest = decl.split(":", 1)
        mode = rest.split()[0].lower()
        w = re.search(r"\(\s*(\d+)\s+downto\s+0\s*\)", rest, re.I)
        for n in names.split(","):
            ports.append((n.strip(), mode, int(w.group(1)) + 1 if w else None))
    return ports


def harness(top, ports, generics, clk_hz=100_000_000):
    """VHDL for the GUI harness around entity `top`."""
    maps = []
    for name, mode, width in ports:
        key = name.lower()
        if key in BOARD_INPUTS | BOARD_OUTPUTS:
            sig = {"btnc": "btnC", "btnu": "btnU", "btnl": "btnL", "btnr": "btnR", "btnd": "btnD"}.get(key, key)
            if width and key in FULL_WIDTH and width != FULL_WIDTH[key]:
                sig = f"{sig}({width - 1} downto 0)"
            maps.append(f"            {name} => {sig}")
        elif mode == "in":
            raise SystemExit(f"input port '{name}' of {top} is not a Basys3 signal "
                             f"(expected names from the Basys3 master XDC: clk, sw, btnC, btnU, btnL, btnR, btnD)")
        else:
            maps.append(f"            {name} => open")
    gmap = ""
    if generics:
        gmap = "        generic map (" + ", ".join(f"{k} => {v}" for k, v in generics.items()) + ")\n"
    half_ps = round(1e12 / clk_hz / 2)
    has_clk = any(n.lower() == "clk" for n, _, _ in ports)
    return HARNESS.format(top=top, generic_map=gmap, port_map=",\n".join(maps), half_ps=half_ps,
                          clock="" if has_clk else "-- ",
                          clk_mhz=f"{clk_hz / 1e6:g}")


HARNESS = """\
-- Generated by boardsim (basys3_view.py) for the live board view. Don't edit: it is
-- rewritten on every run. Not synthesizable.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use std.textio.all;

entity boardsim_basys3_gui is
    generic (SAMPLES : positive := 250);   -- samples of the outputs per frame
end entity;

architecture sim of boardsim_basys3_gui is
    signal clk     : std_logic := '0';
    signal sw      : std_logic_vector(15 downto 0) := (others => '0');
    signal btnC, btnU, btnL, btnR, btnD : std_logic := '0';
    signal led     : std_logic_vector(15 downto 0) := (others => '0');
    signal seg     : std_logic_vector(6 downto 0) := (others => '1');
    signal dp      : std_logic := '1';
    signal an      : std_logic_vector(3 downto 0) := (others => '1');
    signal running : boolean := true;
begin
    {clock}clk <= not clk after {half_ps} ps when running;   -- {clk_mhz} MHz (the Basys3's oscillator: 100 MHz)

    dut : entity work.{top}
{generic_map}        port map (
{port_map});

    frames : process
        type counts is array (natural range <>) of natural;
        variable l, o : line;
        variable frame_ns, swv, btnv : integer;
        variable led_on : counts(0 to 15);
        variable dig_on : counts(0 to 3);
        variable pattern : std_logic_vector(31 downto 0);   -- 4 digits x (dp & g..a), lit = 1
        function duty(n : natural) return string is
        begin
            return to_hstring(to_unsigned((n * 15 + SAMPLES / 2) / SAMPLES, 4));
        end function;
    begin
        while not endfile(input) loop
            readline(input, l);
            read(l, frame_ns);
            exit when frame_ns <= 0;
            read(l, swv);
            read(l, btnv);
            sw   <= std_logic_vector(to_unsigned(swv, 16));
            btnC <= '1' when btnv mod 2 = 1 else '0';
            btnU <= '1' when (btnv / 2) mod 2 = 1 else '0';
            btnL <= '1' when (btnv / 4) mod 2 = 1 else '0';
            btnR <= '1' when (btnv / 8) mod 2 = 1 else '0';
            btnD <= '1' when (btnv / 16) mod 2 = 1 else '0';
            led_on := (others => 0);
            dig_on := (others => 0);
            pattern := (others => '0');
            for i in 1 to SAMPLES loop
                wait for (frame_ns / SAMPLES) * 1 ns;
                for k in 0 to 15 loop
                    if led(k) = '1' then led_on(k) := led_on(k) + 1; end if;
                end loop;
                for d in 0 to 3 loop
                    if an(d) = '0' then                        -- anodes and segments are active low
                        dig_on(d) := dig_on(d) + 1;
                        pattern(8 * d + 7 downto 8 * d) := not (dp & seg);
                    end if;
                end loop;
            end loop;
            write(o, string'("@b3 "));
            write(o, now / 1 us);
            write(o, ' ');
            for k in 15 downto 0 loop write(o, duty(led_on(k))); end loop;
            write(o, ' ');
            write(o, to_hstring(pattern));
            write(o, ' ');
            for d in 3 downto 0 loop write(o, duty(dig_on(d))); end loop;
            writeline(output, o);
        end loop;
        running <= false;                         -- stop the clock: the simulation ends
        wait;
    end process;
end architecture;
"""


# --- Running it -----------------------------------------------------------------------
class Sim:
    def __init__(self, design, top, hub, frame_ns, realtime):
        self.design, self.top, self.hub = design, top, hub
        self.frame_ns, self.realtime = frame_ns, realtime
        self.sw = 0
        self.btn = 0
        self.proc = None
        self.gen = 0
        self.lock = threading.Lock()

    def start(self):
        with self.lock:
            self.gen += 1
            gen = self.gen
            cmd = [self.design.ghdl, "-r", *self.design.flags, "boardsim_basys3_gui", "--assert-level=failure"]
            self.proc = subprocess.Popen(cmd, cwd=self.design.root, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                         stderr=subprocess.PIPE, text=True, bufsize=1)
            proc = self.proc
        self.hub.publish({"t": "status", "running": True, "code": None})
        threading.Thread(target=self._stderr, args=(proc,), daemon=True).start()
        threading.Thread(target=self._loop, args=(proc, gen), daemon=True).start()

    def stop(self):
        with self.lock:
            proc, self.proc = self.proc, None
            self.gen += 1
        if proc and proc.poll() is None:
            try:
                proc.stdin.write("0 0 0\n")       # ends the harness loop cleanly
                proc.stdin.flush()
                proc.wait(2)
            except (OSError, ValueError, subprocess.TimeoutExpired):
                proc.kill()
                proc.wait()

    def restart(self):
        self.stop()
        self.hub.publish({"t": "reset"})
        self.start()

    def _stderr(self, proc):
        for line in proc.stderr:                  # reports and assertion messages
            self.hub.publish({"t": "uart", "line": line.rstrip()})

    def _loop(self, proc, gen):
        t0, sim0 = time.perf_counter(), None
        speed = 0.0
        try:
            while gen == self.gen:
                sw, btn = self.sw, self.btn       # the inputs this frame is simulated with
                proc.stdin.write(f"{self.frame_ns} {sw} {btn}\n")
                proc.stdin.flush()
                t_frame = time.perf_counter()
                line = proc.stdout.readline()
                if not line:
                    break
                if not line.startswith("@b3 "):
                    self.hub.publish({"t": "uart", "line": line.rstrip()})
                    continue
                _, us, leds, pattern, digits = line.split()
                sim_us = int(us)
                if sim0 is None:
                    sim0, t0 = sim_us, time.perf_counter()
                wall = time.perf_counter() - t_frame
                speed = 0.8 * speed + 0.2 * ((self.frame_ns / 1e9) / wall if wall > 0 else 0)
                self.hub.publish({"t": "state", "us": sim_us, "led": leds, "seg": pattern, "dig": digits,
                                  "sw": sw, "btn": btn, "speed": round(speed, 4)})
                if self.realtime:                 # never run faster than the real board
                    ahead = (sim_us - sim0) / 1e6 - (time.perf_counter() - t0)
                    if ahead > 0:
                        time.sleep(ahead)
        except (OSError, ValueError):
            pass
        code = proc.poll()
        if gen == self.gen:
            self.hub.publish({"t": "status", "running": False, "code": code})


CLOCK_GENERICS = ("clk_hz", "clk_freq", "clk_freq_hz", "clock_hz", "g_clk_hz", "c_clk_hz")


def run(design_dir, top, extra_sim=(), generics=None, clk_hz=None, frame_ms=10.0, realtime=True, port=8738,
        open_browser=True):
    design = ghdl.Design(design_dir, extra_sim=extra_sim)
    src_file, ports, generic_names = find_entity(design.root / "src", top)
    generics = dict(generics or {})

    # Simulating 100 MHz is slow (GHDL manages roughly half a million cycles per second). If the
    # design takes its clock frequency as a generic, run it on a slower clock and tell it
    # so: its dividers shrink and simulated time still matches real time.
    clock_generic = next((g for g in generic_names if g.lower() in CLOCK_GENERICS), None)
    if clk_hz is None:
        clk_hz = 250_000 if clock_generic else 100_000_000
    if clock_generic and clock_generic not in generics:
        generics[clock_generic] = str(int(clk_hz))
    if not any(p[0].lower() == "clk" for p in ports):
        print("No clk port: purely combinational, no clock simulated.")
    elif clk_hz != 100_000_000:
        note = f"generic {clock_generic} = {int(clk_hz)}" if clock_generic else "no clock generic: time runs slow"
        print(f"Clock: {clk_hz / 1e6:g} MHz instead of 100 MHz ({note}); --clk-hz 100e6 for the real clock")
    elif not clock_generic:
        print("Clock: 100 MHz. Tip: give your top entity a CLK_HZ generic (and derive dividers from it):\n"
              "  the board view can then simulate it on a slower clock, much faster.")

    gui = design.build / "gui"
    gui.mkdir(parents=True, exist_ok=True)
    harness_file = gui / "boardsim_basys3_gui.vhd"
    harness_file.write_text(harness(top, ports, generics, clk_hz))

    # Only the design and the harness: the testbenches aren't needed (and may not compile).
    design.work = design.build / "ghdl-gui"
    design.work.mkdir(parents=True, exist_ok=True)
    files = [*sorted((design.root / "src").glob("*.vhd")), harness_file]
    r = subprocess.run([design.ghdl, "-i", *design.flags, *map(str, files)], cwd=design.root,
                       capture_output=True, text=True)
    if r.returncode or not design.elaborate("boardsim_basys3_gui"):
        raise SystemExit(r.stdout + r.stderr + "\nGHDL could not build the design (see above).")

    connected = [p[0] for p in ports if p[0].lower() in BOARD_INPUTS | BOARD_OUTPUTS]
    print(f"{top} ({src_file.name}): {', '.join(connected)}")
    hub = server.Hub()
    sim = Sim(design, top, hub, int(frame_ms * 1e6), realtime)
    sim.start()

    def set_input(body):
        try:
            sw, btn = (int(x) for x in body.split())
        except ValueError:
            return
        sim.sw, sim.btn = sw & 0xFFFF, btn & 0x1F

    hello = {"t": "hello", "top": top, "ports": connected, "frame_ms": frame_ms, "realtime": realtime,
             "clk_hz": clk_hz if "clk" in (c.lower() for c in connected) else 0, "generics": generics}
    server.serve("basys3.html", hub, hello, {"/input": set_input, "/reset": lambda b: sim.restart()},
                 port=port, open_browser=open_browser, on_stop=sim.stop)
    return 0
